<!-- ================= GALLERY SCRIPT ================= -->
<script>

const toggleImages = document.getElementById("toggleImages");
const toggleVideos = document.getElementById("toggleVideos");

let imagesOpen = false;
let videosOpen = false;

toggleImages.onclick = function(){

  const items = document.querySelectorAll(".gallery-images .slide");
  const arrow = this.querySelector(".arrow-down");

  imagesOpen = !imagesOpen;

  items.forEach((item,index)=>{
    if(index >= 4){
      item.style.display = imagesOpen ? "block" : "none";
    }
  });

  arrow.classList.toggle("active");
};

toggleVideos.onclick = function(){

  const items = document.querySelectorAll(".gallery-videos .slide");
  const arrow = this.querySelector(".arrow-down");

  videosOpen = !videosOpen;

  items.forEach((item,index)=>{
    if(index >= 4){
      item.style.display = videosOpen ? "block" : "none";
    }
  });

  arrow.classList.toggle("active");
};

</script>

